-- Locale.lua
-- Localization base (part G).
--
-- DH.L is a lookup table keyed by the original English string. The
-- metatable returns a missing key itself (and caches it), so:
--   * on enUS / enGB clients nothing is ever rewritten - strings stay EN;
--   * every other locale is loaded from its own file (Locale_<code>.lua),
--     listed right after this file in the .toc. Each file checks
--     GetLocale() and rawsets its translations into DH.L.
-- Options.lua / Wizard.lua call L() on labels, headers, dropdown choices
-- and dialog texts at render time.
--
-- Supported WotLK 3.3.5a locales: enUS, enGB, deDE, frFR, esES, esMX,
-- ruRU, ptBR, itIT, koKR, zhCN, zhTW. enUS/enGB use the EN base below;
-- ruRU lives in this file, the rest in Locale_<code>.lua.

local DH = RotationCore
if not DH then return end

local L = setmetatable({}, {
    __index = function(t, k)
        if type(k) ~= "string" then return k end
        rawset(t, k, k)   -- cache: EN shows the original string
        return k
    end,
    })
DH.L = L

